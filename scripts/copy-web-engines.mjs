// Copies the website's on-device engines into public/ so the site serves them itself (no CDN):
//  - public/ocr: Tesseract.js + WebAssembly core + English model (text recognition)
//  - public/ai:  WebLLM runtime + its worker (the optional on-device AI; the model itself is
//                downloaded once on request and kept in the browser)
// No image or text ever leaves the browser. Runs after `npm install` and before every web build.
import { copyFileSync, mkdirSync, statSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';

const require = createRequire(import.meta.url);
const pkgDir = (name) => dirname(require.resolve(`${name}/package.json`, { paths: [process.cwd()] }));
const out = join(process.cwd(), 'public', 'ocr');
mkdirSync(join(out, 'lang'), { recursive: true });

const files = [
  [join(pkgDir('tesseract.js'), 'dist', 'tesseract.min.js'), 'tesseract.min.js'],
  [join(pkgDir('tesseract.js'), 'dist', 'worker.min.js'), 'worker.min.js'],
  // The LSTM engine in three builds; the worker picks the fastest one the browser supports.
  ...['tesseract-core-lstm.wasm.js', 'tesseract-core-simd-lstm.wasm.js', 'tesseract-core-relaxedsimd-lstm.wasm.js'].map((f) => [
    join(pkgDir('tesseract.js-core'), f),
    f,
  ]),
  [join(pkgDir('@tesseract.js-data/eng'), '4.0.0_best_int', 'eng.traineddata.gz'), join('lang', 'eng.traineddata.gz')],
];
let bytes = 0;
for (const [from, to] of files) {
  copyFileSync(from, join(out, to));
  bytes += statSync(from).size;
}
console.log(`copy-web-engines: OCR ${files.length} files (${(bytes / 1e6).toFixed(1)} MB) → public/ocr`);

// On-device AI runtime. The worker runs the model off the page's main thread.
const ai = join(process.cwd(), 'public', 'ai');
mkdirSync(ai, { recursive: true });
copyFileSync(join(pkgDir('@mlc-ai/web-llm'), 'lib', 'index.js'), join(ai, 'web-llm.js'));
writeFileSync(
  join(ai, 'worker.js'),
  `// Runs the on-device AI model in a Web Worker (generated by scripts/copy-web-engines.mjs).
import { WebWorkerMLCEngineHandler } from './web-llm.js';
const handler = new WebWorkerMLCEngineHandler();
self.onmessage = (msg) => handler.onmessage(msg);
`,
);
console.log(`copy-web-engines: AI runtime (${(statSync(join(ai, 'web-llm.js')).size / 1e6).toFixed(1)} MB) → public/ai`);
